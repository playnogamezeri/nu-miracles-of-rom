/**
 * Divine Council secure debate gateway (Cloudflare Worker).
 * Set OPENAI_API_KEY as a Worker secret. Never put it in GitHub Pages.
 * Optional vars: OPENAI_MODEL, ALLOWED_ORIGIN.
 */
const DEFAULT_ORIGIN = "https://playnogamezeri.github.io";
const STAGES = new Set(["positions", "cross-examination", "replies", "synthesis"]);

function corsHeaders(origin, env) {
  const allowed = (env.ALLOWED_ORIGIN || DEFAULT_ORIGIN).split(",").map(x => x.trim());
  const permitted = allowed.includes(origin) || (origin && /^http:\/\/localhost(:\d+)?$/.test(origin));
  return {
    "Access-Control-Allow-Origin": permitted ? origin : "null",
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Vary": "Origin"
  };
}
function json(data, status, cors) {
  return new Response(JSON.stringify(data), { status, headers: { ...cors, "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" } });
}
function safeText(v, max = 5000) { return typeof v === "string" ? v.slice(0, max) : ""; }

function buildInstructions(stage, body) {
  const council = body.council.map((g, i) => ({
    seat: i + 1,
    name: safeText(g.name, 120),
    mastery: safeText(g.job, 1200),
    role: safeText(g.role, 1600),
    function: safeText(g.function, 1600),
    recordedWisdom: safeText(g.wisdom, 2000),
    group: safeText(g.group || g.class, 160)
  }));
  const shared = JSON.stringify({
    question: safeText(body.question, 3000),
    approach: safeText(body.mode, 40),
    council,
    previousRounds: Array.isArray(body.transcript) ? body.transcript.slice(-3).map(x => ({
      round: safeText(x.round, 60),
      response: safeText(x.response, 12000)
    })) : []
  });
  const common = `You are facilitating a fictional, AI-generated deliberation for the Nu Miracles of ROM website.
The user expects a genuine multi-round debate generated by an AI model, but you must be transparent: you are NOT communicating with supernatural beings and must NEVER claim to be a God or to know a God's actual thoughts.
Treat each listed God as a fictional perspective constructed strictly from the supplied pantheon record. Do not invent canon, biography, allegiance, relationships, votes, quotations, or domain details. Do not add Gods. Do not treat recorded wisdom as settled doctrine; it may be draft material.
Ground each perspective in its supplied mastery, role, function, and recorded wisdom. Clearly label every extrapolation as an interpretation or proposal, not a source fact. If a record does not support a claim, say so. Do not force agreement or disagreement. Give distinct arguments where the recorded domains reasonably suggest different priorities; never fabricate conflict just to make drama.
Do not provide instructions for wrongdoing. For high-stakes legal, medical, financial, or safety questions, identify limits and recommend qualified human advice where appropriate.
Write in clear, substantive language. Be candid about uncertainty. Never let a majority vote determine truth. Preserve unresolved issues in the final synthesis.
USER QUESTION AND SOURCE RECORDS (JSON):
${shared}`;

  const stageInstructions = {
    "positions": `ROUND 1 — INDEPENDENT OPENING POSITIONS.
For each council member, produce a distinct opening position. Explain what their recorded domain contributes, what principle or concern that domain highlights, what practical implication follows, and one uncertainty. Do not make all members sound alike. Use a heading for each member. End with a short list of the central questions raised. Do not quote the record unless the exact wording is supplied; paraphrase faithfully.`,
    "cross-examination": `ROUND 2 — CROSS-EXAMINATION.
Each member should ask one pointed, fair question of one or two other members, chosen because their recorded domains raise a genuine tension, missing assumption, or complementary concern. Explain the record-based reason for each question. Do not invent an actual prior belief: address the argument made in Round 1, not a fictional personality. If no meaningful tension is supported, ask a constructive clarifying question instead. Include the questioner, addressee, question, and why it matters.`,
    "replies": `ROUND 3 — REPLIES AND REBUTTALS.
Respond to the questions from Round 2. Each addressed perspective should clarify, qualify, or challenge the argument using its own supplied record. Identify where a criticism is valid, where evidence is missing, and where perspectives can coexist. Do not manufacture consensus or disagreement. Make the strongest fair version of each argument.`,
    "synthesis": `ROUND 4 — CHAIR'S SYNTHESIS.
Produce a careful synthesis: (1) strongest supported insights, (2) points of genuine tension or unresolved questions, (3) practical options with benefits and risks, (4) evidence needed before choosing, (5) a provisional recommendation only if justified, and (6) what remains undecided. Explicitly separate source facts, interpretations, and new proposals. No divine vote, no canonical ruling, and no invented consensus. End with a concise provisional council record.`
  };
  return common + "\n\n" + stageInstructions[stage];
}

export default {
  async fetch(request, env) {
    const origin = request.headers.get("Origin") || "";
    const cors = corsHeaders(origin, env);
    if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });
    if (origin && cors["Access-Control-Allow-Origin"] === "null") return json({ error: "This website origin is not allowed by the debate gateway." }, 403, cors);
    if (request.method !== "POST") return json({ error: "Use POST for debate rounds." }, 405, cors);
    if (!env.OPENAI_API_KEY) return json({ error: "The gateway administrator has not configured OPENAI_API_KEY." }, 503, cors);
    let body;
    try { body = await request.json(); } catch { return json({ error: "Request body must be valid JSON." }, 400, cors); }
    if (!body || !STAGES.has(body.stage)) return json({ error: "Unknown debate round." }, 400, cors);
    if (!safeText(body.question, 3000).trim()) return json({ error: "A question is required." }, 400, cors);
    if (!Array.isArray(body.council) || body.council.length < 1 || body.council.length > 12) return json({ error: "Choose between 1 and 12 council members." }, 400, cors);
    const prompt = buildInstructions(body.stage, body);
    try {
      const upstream = await fetch("https://api.openai.com/v1/responses", {
        method: "POST",
        headers: { "Authorization": "Bearer " + env.OPENAI_API_KEY, "Content-Type": "application/json" },
        body: JSON.stringify({
          model: env.OPENAI_MODEL || "gpt-5",
          instructions: prompt,
          input: "Conduct the requested debate round now. Return a well-structured response in Markdown.",
          max_output_tokens: body.stage === "positions" ? 3200 : 2800
        })
      });
      const data = await upstream.json();
      if (!upstream.ok) {
        const message = data && data.error && data.error.message ? data.error.message : "The AI provider returned an error.";
        return json({ error: message }, upstream.status >= 400 && upstream.status < 600 ? upstream.status : 502, cors);
      }
      let output = data.output_text || "";
      if (!output && Array.isArray(data.output)) {
        output = data.output.flatMap(item => Array.isArray(item.content) ? item.content : [])
          .filter(part => part.type === "output_text").map(part => part.text || "").join("\n");
      }
      if (!output) return json({ error: "The model returned no readable text. Please retry this round." }, 502, cors);
      return json({ stage: body.stage, response: output, model: env.OPENAI_MODEL || "gpt-5" }, 200, cors);
    } catch (error) {
      return json({ error: "Could not reach the AI provider: " + safeText(error.message, 300) }, 502, cors);
    }
  }
};
